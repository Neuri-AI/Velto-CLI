"""Install Velto's native runtime from published Android wheels via p4a."""
from pathlib import Path

# p4a's pinned release only requests the exact NDK API tag. Android wheels
# targeting a lower API are compatible too, so supply those tags explicitly.
_RECIPE = '''# Generated by Velto CLI: install an Android wheel, never a host wheel.
from pythonforandroid.recipe import PyProjectRecipe


class AndroidWheelRecipe(PyProjectRecipe):
    name = {name!r}
    version = None
    site_packages_name = {site!r}

    def get_pip_name(self):
        return {requirement!r}

    def get_pip_install_args(self, arch):
        args = super().get_pip_install_args(arch)
        suffixes = {{"arm64-v8a": ("arm64_v8a", "aarch64"),
                    "x86_64": ("x86_64",),
                    "armeabi-v7a": ("arm",), "x86": ("i686",)}}[arch.arch]
        for api in range(21, self.ctx.ndk_api):
            args.extend("--platform=android_{{}}_{{}}".format(api, suffix)
                        for suffix in suffixes)
        return args

    def build_arch(self, arch):
        if not self.install_prebuilt_wheel(arch):
            raise RuntimeError("No compatible Android wheel for " + self.name)


recipe = AndroidWheelRecipe()
'''


def configure_velto_wheel_recipes(recipe_dir: Path) -> None:
    definitions = (
        # p4a compares normalized distribution names against recipe names
        # without normalizing the latter. Use underscores so it recognizes
        # Cinnamon as already installed and does not feed its Android wheel
        # to the host-platform pip a second time.
        ('velto_cinnamon_core', '_sfle_native', 'velto-cinnamon-core>=0.1.1,<1.0.0'),
        ('resvg_py', 'resvg_py', 'resvg_py>=0.5,<0.6'),
    )
    for name, site, requirement in definitions:
        recipe = recipe_dir / name / '__init__.py'
        if recipe.exists() and not recipe.read_text(encoding='utf-8').startswith(
            '# Generated by Velto CLI:'
        ):
            raise RuntimeError(f'Refusing to overwrite custom Android recipe: {recipe}')
        recipe.parent.mkdir(parents=True, exist_ok=True)
        recipe.write_text(_RECIPE.format(name=name, site=site, requirement=requirement),
                          encoding='utf-8')
